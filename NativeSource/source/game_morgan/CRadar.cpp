uint32_t CRadar::GetRadarTraceColor(uintptr_t /*thiz*/, uint32_t color)
{
	if (color >= 0xFFFFFFFF) {
        return 0xFFFFFFFF;
    }
	
    return CRadar::TranslateColorCodeToRGBA((int)color);
}

void CRadar::SetRadarColor(int nIndex, uint32_t dwColor)
{
	if (ARRAY_VALIDATE(dwUseHudColors, nIndex))
	{
		dwUseHudColors[nIndex] = dwColor;
	}
}

void CRadar::ResetRadarColor()
{
    memcpy(&dwUseHudColors[0], &dwHudColors[0], sizeof(uint32_t) * NUM_RADAR_COLORS);
}

uint32_t CRadar::TranslateColorCodeToRGBA(int iCode)
{
	if (iCode < 0) {
        return 0xFFFFFFFF;
    }

	switch (iCode)
	{
		case 1004:
		return 0x89A4C440;

		case 1005:
		return 0xAA0000FF;

		case 1006:
		return 0xE2C063FF;
	}

	if (iCode < NUM_RADAR_COLORS)
    {
        return dwUseHudColors[iCode];
    }
		
	return iCode;
}

